<?php

use App\Actions\Tasks\ImportTasksAction;
use App\Actions\Tasks\ParseTaskImportAction;
use App\Data\ParsedTaskLineData;
use App\Models\Project;
use App\Models\Task;
use Flux\Flux;
use Illuminate\Support\Str;
use Livewire\Attributes\Locked;
use Livewire\Component;

new class extends Component
{
    public Project $project;
    public string $text = '';

    #[Locked]
    public int $step = 1;

    /**
     * @var array<ParsedTaskLineData>
     */
    #[Locked]
    public array $parsedLines = [];

    public function mount(Project $project): void
    {
        $this->authorize('view', $project);

        $this->project = $project;
    }

    public function preview(ParseTaskImportAction $parser): void
    {
        $this->authorize('view', $this->project);

        $nonBlank = $this->nonBlankLines();

        if (empty($nonBlank)) {
            $this->addError('text', 'Please enter at least one task line.');

            return;
        }

        if (count($nonBlank) > ParseTaskImportAction::MAX_LINES) {
            $this->addError('text', 'The text cannot contain more than '.ParseTaskImportAction::MAX_LINES.' tasks.');

            return;
        }

        $this->resetErrorBag();
        $this->parsedLines = $parser->execute($this->project, $this->text);
        $this->step = 2;
    }

    public function back(): void
    {
        $this->step = 1;
    }

    public function import(ImportTasksAction $importer, ParseTaskImportAction $parser): void
    {
        $this->authorize('create', [Task::class, $this->project]);

        $nonBlank = $this->nonBlankLines();

        if (empty($nonBlank)) {
            $this->addError('text', 'Please enter at least one task line.');

            return;
        }

        if (count($nonBlank) > ParseTaskImportAction::MAX_LINES) {
            $this->addError('text', 'The text cannot contain more than '.ParseTaskImportAction::MAX_LINES.' tasks.');

            return;
        }

        $parsedLines = $parser->execute($this->project, $this->text);
        $validCount = count(array_filter($parsedLines, fn (ParsedTaskLineData $line): bool => $line->isValid()));

        $importer->execute($this->project, $parsedLines, auth()->user());

        Flux::toast("{$validCount} tasks imported", variant: 'success');
        Flux::modal('import-tasks-modal-'.$this->project->id)->close();

        $this->reset(['text', 'parsedLines', 'step']);
        $this->dispatch('task-created');
    }

    /**
     * @return array<string>
     */
    private function nonBlankLines(): array
    {
        $rawLines = preg_split('/\r\n|\r|\n/', $this->text) ?: [];

        return array_filter(array_map('trim', $rawLines));
    }

    public function with(): array
    {
        $validCount = count(array_filter($this->parsedLines, fn (ParsedTaskLineData $line): bool => $line->isValid()));

        return [
            'validCount' => $validCount,
            'totalCount' => count($this->parsedLines),
        ];
    }
};
?>

<div>
    <flux:modal.trigger name="import-tasks-modal-{{ $project->id }}">
        <flux:button size="sm" icon="arrow-up-tray" variant="ghost">Import</flux:button>
    </flux:modal.trigger>

    <flux:modal name="import-tasks-modal-{{ $project->id }}" class="w-4xl space-y-6">
        <div>
            <flux:heading size="lg">Import Tasks from NotebookLM</flux:heading>
            <flux:text class="mt-1">
                Paste task lines generated by NotebookLM to bulk-create tasks in this project.
            </flux:text>
        </div>

        @if($step === 1)
            <div class="space-y-4">
                <flux:field>
                    <flux:label>Task lines</flux:label>
                    <flux:textarea
                        rows="12"
                        wire:model="text"
                        placeholder="- [ ] [AREA] Title — acceptance criterion — depende de: X"
                        class="font-mono text-sm"
                    />
                    <flux:error name="text" />
                </flux:field>

                <flux:text size="sm" class="text-zinc-500">
                    Format: <code>- [ ] [AREA] Title — acceptance criterion — depende de: X</code> (max {{ ParseTaskImportAction::MAX_LINES }} tasks)
                </flux:text>

                <div class="flex justify-end gap-2 pt-2">
                    <flux:modal.close>
                        <flux:button variant="ghost">Cancel</flux:button>
                    </flux:modal.close>
                    <flux:button variant="primary" wire:click="preview">Preview</flux:button>
                </div>
            </div>
        @else
            <div class="space-y-4">
                <div class="max-h-[28rem] overflow-y-auto border border-zinc-200 dark:border-zinc-800 rounded-lg">
                    <flux:table>
                        <flux:table.columns>
                            <flux:table.column>Area</flux:table.column>
                            <flux:table.column>Title</flux:table.column>
                            <flux:table.column>Acceptance Criterion</flux:table.column>
                            <flux:table.column>Dependency</flux:table.column>
                            <flux:table.column>Status / Warnings</flux:table.column>
                        </flux:table.columns>
                        <flux:table.rows>
                            @foreach($parsedLines as $index => $line)
                                <flux:table.row :key="'parsed-line-'.$index" class="{{ ! $line->isValid() ? 'bg-red-50/50 dark:bg-red-950/20' : '' }}">
                                    <flux:table.cell>
                                        @if($line->areaName)
                                            <flux:badge size="sm" :color="$line->areaColor ?? 'zinc'">{{ $line->areaName }}</flux:badge>
                                        @elseif($line->areaTag)
                                            <flux:badge size="sm" color="zinc">{{ $line->areaTag }}</flux:badge>
                                        @else
                                            <span class="text-xs text-zinc-400">None</span>
                                        @endif
                                    </flux:table.cell>
                                    <flux:table.cell class="font-medium">
                                        <div class="flex items-center gap-1.5">
                                            @if($line->status === \App\Enums\TaskStatus::Done)
                                                <flux:badge size="sm" color="green">Done</flux:badge>
                                            @endif
                                            <span>{{ $line->title ?: '—' }}</span>
                                        </div>
                                    </flux:table.cell>
                                    <flux:table.cell class="text-sm text-zinc-600 dark:text-zinc-300">
                                        {{ $line->criterion ?: '—' }}
                                    </flux:table.cell>
                                    <flux:table.cell class="text-xs text-zinc-500 font-mono">
                                        {{ $line->dependency ?: '—' }}
                                    </flux:table.cell>
                                    <flux:table.cell>
                                        @if(! $line->isValid())
                                            <div class="space-y-1">
                                                @foreach($line->errors as $error)
                                                    <div class="flex items-center gap-1 text-xs text-red-600 dark:text-red-400">
                                                        <flux:icon.exclamation-circle class="w-3.5 h-3.5" />
                                                        <span>{{ $error }}</span>
                                                    </div>
                                                @endforeach
                                            </div>
                                        @elseif($line->hasWarnings())
                                            <div class="space-y-1">
                                                @foreach($line->warnings as $warning)
                                                    <div class="flex items-center gap-1 text-xs text-amber-600 dark:text-amber-400">
                                                        <flux:icon.exclamation-triangle class="w-3.5 h-3.5" />
                                                        <span>{{ $warning }}</span>
                                                    </div>
                                                @endforeach
                                            </div>
                                        @else
                                            <flux:badge size="sm" color="green">Ready</flux:badge>
                                        @endif
                                    </flux:table.cell>
                                </flux:table.row>
                            @endforeach
                        </flux:table.rows>
                    </flux:table>
                </div>

                <div class="flex justify-between items-center pt-2">
                    <flux:button variant="ghost" wire:click="back">Back</flux:button>
                    <div class="flex items-center gap-2">
                        <flux:modal.close>
                            <flux:button variant="ghost">Cancel</flux:button>
                        </flux:modal.close>
                        <flux:button
                            variant="primary"
                            wire:click="import"
                            :disabled="$validCount === 0"
                        >
                            Import {{ $validCount }} {{ Str::plural('task', $validCount) }}
                        </flux:button>
                    </div>
                </div>
            </div>
        @endif
    </flux:modal>
</div>